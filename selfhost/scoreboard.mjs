// selfhost/scoreboard.mjs — rederive's self re-derivation, one row per unit, read from the units themselves (never hand-kept):
// STAGE.json (the authority the oracle was stamped from), runs/decision.json (the last grade), and the file times that say
// whether that grade is still about this contract. A unit is VERIFIED only when its last grade accepted (every language in
// quorum with every rung, cross-verified where it has two or more languages) AND that grade is newer than its contract and
// oracle — a re-cut after the grade makes it PENDING again, however good the old grade was. Writes selfhost/SCOREBOARD.md.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const auth = JSON.parse(readFileSync(join(HERE, 'AUTHORITY.json'), 'utf8'));
const mtime = (p) => (existsSync(p) ? statSync(p).mtimeMs : 0);
const rows = [];
for (const unit of readdirSync(join(HERE, 'units')).sort()) {
  const dir = join(HERE, 'units', unit); const stage = JSON.parse(readFileSync(join(dir, 'STAGE.json'), 'utf8'));
  const tier = /Tier (\d)/.exec(stage.note ?? '')?.[1] ?? '1';
  const dp = join(dir, 'runs', 'decision.json'); const d = existsSync(dp) ? JSON.parse(readFileSync(dp, 'utf8')) : null;
  const sirDir = join(dir, 'sir'); const contract = Math.max(0, ...(existsSync(sirDir) ? readdirSync(sirDir).filter((f) => f.endsWith('.sir')).map((f) => mtime(join(sirDir, f))) : []), mtime(join(dir, 'oracles', `${unit}.json`)));
  const fresh = d && mtime(dp) >= contract;
  const status = existsSync(join(dir, 'SUPERSEDED.md')) ? 'RETIRED (SUPERSEDED.md)' : !d ? 'PENDING (never graded)' : !fresh ? 'PENDING (re-cut since the last grade)' : d.next === 'accept' ? 'VERIFIED' : d.next === 'quarantine' ? 'QUARANTINED' : `PENDING (${d.next})`;
  const lang = (l) => { const p = d?.perLang?.[l]; return !p ? '—' : p.status ? p.status.slice(0, 18) : p.quorum; };
  rows.push({ unit, tier, from: (stage.source ?? '').replace('rederive@', ''), status, js: lang('js'), ts: lang('ts'), rust: lang('rust'), cross: d?.cross ? d.cross.agree : '—', round: d?.round ?? '—' });
}
const count = (s) => rows.filter((r) => r.status === s).length;
const live = rows.filter((r) => !r.status.startsWith('RETIRED'));
const byTier = (t) => { const rs = live.filter((r) => r.tier === t); return `${rs.filter((r) => r.status === 'VERIFIED').length} of ${rs.length}`; };
const md = `# Selfhost scoreboard (REDERIVE_SELF_PLAN)

Generated by \`node selfhost/scoreboard.mjs\` from each unit's STAGE.json and runs/decision.json — never edited by hand. The current
authority is rederive@${auth.commit} (selfhost/AUTHORITY.json); a unit stamped from an older one is still valid while
selfhost/regress.test.mjs passes (the live kernel reproduces every vector it pinned).

**${count('VERIFIED')} of ${live.length} VERIFIED** — Tier 1 ${byTier('1')} · Tier 2 ${byTier('2')} · Tier 3 ${byTier('3')}${count('QUARANTINED') ? ` · ${count('QUARANTINED')} quarantined` : ''}

| unit | tier | status | js | ts | rust | cross | round | stamped from |
|---|---|---|---|---|---|---|---|---|
${rows.map((r) => `| ${r.unit} | ${r.tier} | ${r.status} | ${r.js} | ${r.ts} | ${r.rust} | ${r.cross} | ${r.round} | ${r.from} |`).join('\n')}
`;
writeFileSync(join(HERE, 'SCOREBOARD.md'), md);
console.log(md.split('\n').slice(0, 8).join('\n'));
